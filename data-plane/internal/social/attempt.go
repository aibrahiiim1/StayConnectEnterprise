package social

// THE PER-ATTEMPT SECRETS: PKCE AND THE OIDC NONCE (contract docs/architecture/ONEGATE_HTTPS_PORTAL_AND_SOCIAL_LOGIN.md §5).
//
// `state` binds the browser's return to the device that started (scd's social_oauth_states row). These two
// bind the PROVIDER'S ANSWER to that same attempt:
//
//   - PKCE S256 (RFC 7636; Google, Microsoft). The authorize request carries BASE64URL(SHA256(verifier)); the
//     token request must carry the verifier. A code that leaks out of the browser leg -- a captive browser's
//     history, a referrer, a shared screen -- cannot be redeemed by anyone but scd, which never sent the
//     verifier anywhere but the provider's token endpoint.
//   - The OIDC nonce (Google, Microsoft, Apple). The id_token must repeat the nonce of this attempt. An
//     id_token minted for another sign-in -- another device, another attempt of this one -- is refused even
//     though its signature, issuer and audience are perfect.
//
// Both are generated by scd at the start of the attempt, stored with the state row, and used once.

import (
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"fmt"
)

// NewAttemptSecrets returns a fresh PKCE verifier and/or OIDC nonce for the bindings a provider uses (an empty
// string for each one it does not). Each is 32 crypto-random bytes, base64url without padding: 43 characters
// of RFC 7636's unreserved alphabet, the minimum verifier length that standard allows and 256 bits of entropy.
func NewAttemptSecrets(b Binding) (verifier, nonce string, err error) {
	if b.PKCE {
		if verifier, err = random43(); err != nil {
			return "", "", err
		}
	}
	if b.Nonce {
		if nonce, err = random43(); err != nil {
			return "", "", err
		}
	}
	return verifier, nonce, nil
}

func random43() (string, error) {
	var b [32]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b[:]), nil
}

// PKCEChallengeS256 is the RFC 7636 §4.2 S256 transform: BASE64URL-ENCODE(SHA256(ASCII(code_verifier))).
func PKCEChallengeS256(verifier string) string {
	sum := sha256.Sum256([]byte(verifier))
	return base64.RawURLEncoding.EncodeToString(sum[:])
}

// requireBinding refuses an exchange that does not carry what the provider binds an attempt with. A state row
// written before this existed has neither; it expires within ten minutes and its sign-in simply starts again.
func requireBinding(b Binding, x ExchangeRequest) error {
	if b.PKCE && x.CodeVerifier == "" {
		return fmt.Errorf("%w: no PKCE verifier", ErrAttemptBinding)
	}
	if b.Nonce && x.Nonce == "" {
		return fmt.Errorf("%w: no nonce", ErrAttemptBinding)
	}
	return nil
}

// checkNonce compares the id_token's nonce with the attempt's in constant time. The nonce is not a long-lived
// secret, but it is the value an attacker would have to guess, so the comparison gives no timing hint.
func checkNonce(c *idClaims, want string) error {
	got := c.str("nonce")
	if want == "" || got == "" || subtle.ConstantTimeCompare([]byte(got), []byte(want)) != 1 {
		return fmt.Errorf("%w: id_token nonce does not match this sign-in attempt", ErrAttemptBinding)
	}
	return nil
}
